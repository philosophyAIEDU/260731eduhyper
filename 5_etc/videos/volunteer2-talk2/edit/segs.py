import re,json
t=open('../../../../1_작업할 영상/봉사단2기 두번째 발표 자막.srt',encoding='utf-8-sig').read()
def ts(s):
  m=re.match(r'(\d+):(\d+):(\d+),(\d+)',s);return int(m[1])*3600+int(m[2])*60+int(m[3])+int(m[4])/1000
C={}
for b in re.split(r'\n\s*\n',t.strip()):
  l=b.split('\n');a,e=l[1].split(' --> ');C[int(l[0])]=(ts(a),ts(e),' '.join(l[2:]))
R=[(1,40),(54,62),(72,94),(125,135),(144,145),(154,178),(179,194),(207,218),(219,238),(248,266),(269,283),(296,305),
(312,322),(328,339),(370,373),(374,376),(381,403),(404,427),(432,466),(467,486),(487,508),(519,537),(540,543),(548,561),
(562,582),(587,618),(623,633),(653,659),(661,673),(675,686),(693,700),(714,733),(734,752),(763,765),(772,790),(795,815),(816,847),(860,867),(975,977)]
tot=0;segs=[]
for a,b in R:
  s=C[a][0]; e=C[b][1]
  segs.append({'a':a,'b':b,'s':round(s,3),'e':round(e,3)}); tot+=e-s
print(round(tot/60,2))
json.dump({'segs':segs,'cues':{k:v for k,v in C.items()}},open('cuts.json','w',encoding='utf-8'),ensure_ascii=False)
